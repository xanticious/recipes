function isAnimal(item: Ingredient): boolean {
  if (item.kind === "dairy") {
    return true;
  }
  if (item.kind === "protein") {
    return !PLANT_PROTEINS.has(item.id);
  }
  return OTHER_ANIMAL.has(item.id);
}

function isNotKeto(item: Ingredient): boolean {
  if (item.kind === "grain") {
    return !KETO_OK_GRAINS.has(item.id);
  }
  if (item.kind === "sweetener") {
    return !KETO_SWEETENERS.has(item.id);
  }
  return NOT_KETO_IDS.has(item.id);
}

function isNotPaleo(item: Ingredient): boolean {
  if (item.kind === "dairy") {
    return true;
  }
  if (item.kind === "grain") {
    return !PALEO_OK_GRAINS.has(item.id);
  }
  return NOT_PALEO_IDS.has(item.id);
}

function isNotCarnivore(item: Ingredient): boolean {
  if (item.kind === "dairy") {
    return false;
  }
  return !CARNIVORE_OK.has(item.id);
}

export function lifestyleFlagsFor(item: Ingredient): IngredientFlag[] {
  const flags: IngredientFlag[] = [];
  if (isAnimal(item)) {
    flags.push("animal");
  }
  if (isNotKeto(item)) {
    flags.push("not-keto");
  }
  if (isNotPaleo(item)) {
    flags.push("not-paleo");
  }
  if (isNotCarnivore(item)) {
    flags.push("not-carnivore");
  }
  return flags;
}

export function withLifestyleFlags(item: Ingredient): Ingredient {
  const flags = [...item.flags];
  for (const flag of lifestyleFlagsFor(item)) {
    if (!flags.includes(flag)) {
      flags.push(flag);
    }
  }
  return { ...item, flags };
}
